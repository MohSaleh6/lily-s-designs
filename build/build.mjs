/**
 * Static site generator.
 *
 * Composes the seven pages from shared partials so the header, footer and
 * overlays are byte-identical everywhere, renders every SVG asset, and emits
 * the sitemap, robots.txt and web manifest. Output lands in the repo root so
 * the site can be served straight from GitHub Pages with no build step.
 *
 *   node build/build.mjs
 */
import { writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { site, cards, testimonials, occasions, plans, addons, ui } from './content.mjs';
import { cardSVG, squareSVG, sceneSVG, portraitSVG, ogSVG, faviconSVG } from './art.mjs';
import { home, portfolio, services, about, testimonialsPage } from './pages.mjs';
import { order, contact } from './pages-order.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (...p) => join(root, ...p);

const MOTIF_BY_OCCASION = {
  wedding: 'rings', eid: 'eid', birthday: 'confetti', graduation: 'laurel',
  corporate: 'grid', newborn: 'botanical', thanks: 'botanical'
};

let written = 0;
function write(relPath, contents) {
  const target = out(relPath);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, contents, 'utf8');
  written++;
}

/* ------------------------------------------------------------ pages */

const pages = [
  ['index.html', home()],
  ['portfolio.html', portfolio()],
  ['services.html', services()],
  ['order.html', order()],
  ['about.html', about()],
  ['testimonials.html', testimonialsPage()],
  ['contact.html', contact()]
];
pages.forEach(([name, html]) => write(name, html));

/* --------------------------------------------------------- artwork */

rmSync(out('assets/img/cards'), { recursive: true, force: true });
rmSync(out('assets/img/square'), { recursive: true, force: true });
rmSync(out('assets/img/reviews'), { recursive: true, force: true });

cards.forEach((c) => {
  write(`assets/img/cards/${c.id}.svg`, cardSVG({
    id: c.id, palette: c.palette, motif: c.motif || MOTIF_BY_OCCASION[c.occasion] || 'rings'
  }));
});

['hilal-eid', 'ward-blush', 'mabrouk-grad', 'corporate-navy'].forEach((id) => {
  const c = cards.find((x) => x.id === id);
  write(`assets/img/square/${id}.svg`, squareSVG({ id: `sq-${id}`, palette: c.palette, motif: c.motif }));
});

testimonials.forEach((t) => {
  write(`assets/img/reviews/${t.id}.svg`, sceneSVG({ id: `rev-${t.id}`, palette: t.palette }));
});

write('assets/img/brand/studio.svg', portraitSVG({ id: 'studio' }));
write('assets/img/brand/og-card.svg', ogSVG());
write('assets/img/brand/favicon.svg', faviconSVG());

/* ---------------------------------------------- runtime data island */

/* The catalogue the browser scripts read: lightbox copy, cart prices and the
   order estimate all come from here, so the markup and the runtime can never
   drift apart. */
const runtime = {
  site: {
    name: site.name,
    phoneIntl: site.phoneIntl,
    phoneLocal: site.phoneLocal,
    phoneE164: site.phoneE164,
    email: site.email,
    instagram: site.instagram,
    instagramUrl: site.instagramUrl
  },
  ui,
  occasions,
  cards: cards.map((c) => ({
    id: c.id, occasion: c.occasion, price: c.price,
    en: { title: c.en.title, desc: c.en.desc, tags: c.tags.en },
    ar: { title: c.ar.title, desc: c.ar.desc, tags: c.tags.ar }
  })),
  plans: plans.map((p) => ({
    id: p.id, price: p.price, minQty: p.minQty, pricing: p.pricing,
    name: p.name, turnaround: p.turnaround
  })),
  addons: addons.map((x) => ({ id: x.id, price: x.price, en: x.en.name, ar: x.ar.name })),
  delivery: { whatsapp: 0, amman: 3, shipping: 0, pickup: 0 }
};

write('assets/js/data.js', '/* Generated by build/build.mjs — do not edit by hand. */\nwindow.LD = ' +
  JSON.stringify(runtime, null, 2) + ';\n');

/* ------------------------------------------------ crawler artefacts */

const today = new Date().toISOString().slice(0, 10);
const urls = pages.map(([name]) => {
  const priority = name === 'index.html' ? '1.0' : name === 'order.html' ? '0.9' : '0.8';
  return `  <url>
    <loc>${site.url}/${name}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${priority}</priority>
  </url>`;
}).join('\n');

write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`);

write('robots.txt', `User-agent: *
Allow: /

Sitemap: ${site.url}/sitemap.xml
`);

write('site.webmanifest', JSON.stringify({
  name: `${site.name.en} — ${site.name.ar}`,
  short_name: site.name.en,
  description: 'Bespoke Arabic greeting cards, designed in Amman.',
  start_url: './index.html',
  scope: './',
  display: 'standalone',
  background_color: '#FBF8F4',
  theme_color: '#0E4C41',
  lang: 'ar',
  dir: 'rtl',
  icons: [
    { src: 'assets/img/brand/favicon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' }
  ]
}, null, 2) + '\n');

/* GitHub Pages must not run these files through Jekyll. */
write('.nojekyll', '');

console.log(`Built ${pages.length} pages and ${written - pages.length} assets (${written} files).`);
